#!/usr/bin/env python3
"""Builds MimeTable.kt: MIME name (and aliases) -> first glob pattern, as
QMimeDatabase().mimeTypeForName(name).globPatterns().front() returns it in
Qt 6 builds that bundle Apache Tika's mimetypes (Windows/macOS Desktop)."""
import sys
import xml.etree.ElementTree as ET

src, out = sys.argv[1], sys.argv[2]
root = ET.parse(src).getroot()
ns = ""
first = {}
alias = {}
for mt in root.iter(ns + "mime-type"):
    name = mt.get("type")
    globs = [g.get("pattern") for g in mt.findall(ns + "glob")]
    if globs and name not in first:
        first[name] = globs[0]
    for a in mt.findall(ns + "alias"):
        alias[a.get("type")] = name

def kt(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

lines = ["// Generated by tools/mimegen.py from tools/tika-mimetypes.xml. Do not edit.",
         "package org.tgbackup.export.data", "",
         "internal object MimeTable {",
         "    /** Canonical MIME name -> first glob pattern. */",
         "    val firstGlob: Map<String, String> = HashMap<String, String>(%d).apply {" % (len(first) * 2)]
items = sorted(first.items())
for i in range(0, len(items), 200):
    lines.append("        fill%d(this)" % (i // 200))
lines.append("    }")
lines.append("")
lines.append("    /** Alias -> canonical MIME name. */")
lines.append("    val aliases: Map<String, String> = hashMapOf(")
for a, c in sorted(alias.items()):
    lines.append("        %s to %s," % (kt(a), kt(c)))
lines.append("    )")
for i in range(0, len(items), 200):
    lines.append("")
    lines.append("    private fun fill%d(m: HashMap<String, String>) {" % (i // 200))
    for k, v in items[i:i + 200]:
        lines.append("        m[%s] = %s" % (kt(k), kt(v)))
    lines.append("    }")
lines.append("}")
open(out, "w").write("\n".join(lines) + "\n")
print(len(first), "types", len(alias), "aliases")
